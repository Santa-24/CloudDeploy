import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import { authService } from '../services/authService';
import { Input } from '../components/Input';
import { Button } from '../components/Button';
import { useToast } from '../components/Toast';
import { ArrowLeft, Mail, CheckCircle2 } from 'lucide-react';

export const ForgotPasswordPage: React.FC = () => {
  const [email, setEmail] = useState('');
  const [isSubmitted, setIsSubmitted] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const toast = useToast();

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsLoading(true);
    try {
      await authService.requestPasswordReset(email);
      setIsSubmitted(true);
      toast.success('Recovery Code Dispatched', `Check ${email} for confirmation code.`);
    } catch (err: any) {
      toast.error('Request Failed', err?.message || 'Could not initiate password recovery');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="min-h-[80vh] flex items-center justify-center py-12 px-4 sm:px-6 lg:px-8 bg-paper">
      <div className="max-w-md w-full">
        <div className="text-center mb-8">
          <h2 className="font-editorial text-3xl font-bold tracking-tight text-ink">
            Reset Password
          </h2>
          <p className="mt-2 text-xs font-mono text-ink-muted">
            Cognito Identity Recovery Protocol
          </p>
        </div>

        <div className="card-editorial p-8 bg-paper-light">
          {isSubmitted ? (
            <div className="text-center space-y-4">
              <CheckCircle2 className="w-12 h-12 text-green-700 mx-auto" />
              <h3 className="font-editorial text-xl font-bold text-ink">
                Recovery Code Sent
              </h3>
              <p className="text-xs font-mono text-ink-muted">
                If an active account exists for <strong>{email}</strong>, Amazon Cognito has dispatched a verification code to complete password recovery.
              </p>
              <Link to="/login" className="inline-block mt-4">
                <Button variant="secondary" size="sm" leftIcon={<ArrowLeft className="w-4 h-4" />}>
                  Back to Sign In
                </Button>
              </Link>
            </div>
          ) : (
            <form onSubmit={handleSubmit} className="space-y-4">
              <p className="text-xs text-ink-muted mb-2">
                Enter your registered workspace email. A password reset token will be generated by Amazon Cognito User Pool.
              </p>
              <Input
                label="Email Address"
                type="email"
                required
                value={email}
                onChange={e => setEmail(e.target.value)}
                placeholder="architect@clouddeploy.internal"
                leftIcon={<Mail className="w-4 h-4" />}
              />
              <Button
                type="submit"
                variant="primary"
                className="w-full mt-2"
                isLoading={isLoading}
              >
                Send Recovery Instructions
              </Button>
              <div className="text-center pt-2">
                <Link to="/login" className="text-xs font-mono text-ink-muted hover:text-ink">
                  ← Return to Login
                </Link>
              </div>
            </form>
          )}
        </div>
      </div>
    </div>
  );
};
